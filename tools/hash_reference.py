#!/usr/bin/env python3
"""Reference values for the stable hash of sim-core (ADR-0003, section 5.1).

xxh3-64 with seed 0, computed by the C reference implementation libxxhash (through the
pinned PyPI package xxhash, see tools/requirements.txt), independent of the Rust crate
xxhash-rust that sim-core uses. The inputs cover every length class of xxh3 and the
str_key known answers of ADR-0004.

Writes tests/golden/kat/xxh3_64.csv (protected list, ADR-0000).
Usage: .venv/bin/python tools/hash_reference.py
"""

from pathlib import Path

import xxhash

OUT = Path(__file__).resolve().parent.parent / "tests" / "golden" / "kat" / "xxh3_64.csv"

# Length classes of xxh3: 0, 1-3, 4-8, 9-16, 17-128, 129-240, above 240 (with the
# boundaries on both sides).
LENGTHS = [0, 1, 2, 3, 4, 7, 8, 9, 15, 16, 17, 64, 127, 128, 129, 200, 240, 241, 500, 1024, 4099]

STRINGS = [b"core:height", b"test:fork_no_density"]


def pattern(n: int) -> bytes:
    return bytes((i * 31 + 7) % 256 for i in range(n))


def main() -> None:
    assert xxhash.XXHASH_VERSION == "0.8.3", xxhash.XXHASH_VERSION
    rows = []
    for data in [pattern(n) for n in LENGTHS] + STRINGS:
        rows.append(f"{data.hex()},{xxhash.xxh3_64_intdigest(data):016x}")
    lines = [
        "# generated by tools/hash_reference.py (libxxhash 0.8.3), do not edit by hand (ADR-0003)",
        "input_hex,xxh3_64",
    ] + rows
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(rows)} rows")


if __name__ == "__main__":
    main()
