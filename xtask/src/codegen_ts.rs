//! The TypeScript types of the body contract for `web/` (ADR-0005 section 2, ADR-0021
//! section 4): `cargo xtask codegen` writes them from `contracts/body.json` beside the Rust
//! types, and the contract check of the gate compares the checked-in file with a fresh
//! generation. The file holds data only: the keys, each parameter's group, unit, range and
//! default, and the sRGB grids of the melanin rule, which `web/` reads and never computes.

use std::fmt::Write;

use serde_json::Value;

use crate::contract;

/// Where the generated types live, relative to the repository root.
pub const GENERATED_TS: &str = "web/src/generated/body.ts";

/// A JSON value as a TypeScript literal: JSON is one.
fn literal(value: &Value) -> String {
    value.to_string()
}

/// The TypeScript module of the contract in `body_json`, or the findings of its schema.
pub fn generate(body_json: &str) -> Result<String, Vec<String>> {
    let findings = contract::schema_findings(body_json);
    if !findings.is_empty() {
        return Err(findings);
    }
    let body: Value = serde_json::from_str(body_json).map_err(|error| vec![error.to_string()])?;
    let empty = Vec::new();
    let parameters = body["parameters"].as_array().unwrap_or(&empty);
    let mut out = String::new();
    // Writing into a String cannot fail.
    let mut line = |text: &str| {
        let _ = writeln!(out, "{text}");
    };
    line("// Generated by `cargo xtask codegen` from contracts/body.json. Do not edit.");
    line("");
    line("/** The version of the body contract these types follow (ADR-0005). */");
    line(&format!(
        "export const BODY_CONTRACT_VERSION = {};",
        literal(&body["contract_version"])
    ));
    line("");
    line("/** The keys of the body parameters, in the order of the contract. */");
    line("export const BODY_PARAM_KEYS = [");
    for parameter in parameters {
        line(&format!("  {},", literal(&parameter["key"])));
    }
    line("] as const;");
    line("");
    line("export type BodyParamKey = (typeof BODY_PARAM_KEYS)[number];");
    line("");
    line("/** One value per parameter, in its unit; the core computes them, `web/` shows them. */");
    line("export type BodyParams = { readonly [K in BodyParamKey]: number };");
    line("");
    line("export type BodyParam = {");
    line("  readonly group: string;");
    line("  readonly unit: string;");
    line("  readonly min: number;");
    line("  readonly max: number;");
    line("  readonly default: number;");
    line("};");
    line("");
    line("/** Each parameter's group, unit, range and default, as the contract states them. */");
    line("export const BODY_PARAMS: { readonly [K in BodyParamKey]: BodyParam } = {");
    for parameter in parameters {
        line(&format!(
            "  {}: {{ group: {}, unit: {}, min: {}, max: {}, default: {} }},",
            literal(&parameter["key"]),
            literal(&parameter["group"]),
            literal(&parameter["unit"]),
            literal(&parameter["range"][0]),
            literal(&parameter["range"][1]),
            literal(&parameter["default"]),
        ));
    }
    line("};");
    line("");
    line("/**");
    line(" * The sRGB grids of the melanin rule (ADR-0005 section 5): per material the points of");
    line(" * eumelanin and pheomelanin and the colour at each pair, rows by eumelanin. Readers");
    line(" * linearise and interpolate bilinearly between the points.");
    line(" */");
    line("export const MELANIN_TO_SRGB = {");
    let tables = body["melanin_to_srgb"].as_object();
    for (material, table) in tables.into_iter().flatten() {
        line(&format!(
            "  {}: {{",
            literal(&Value::from(material.as_str()))
        ));
        for field in ["eumelanin", "pheomelanin"] {
            line(&format!("    {field}: {},", literal(&table[field])));
        }
        line("    srgb: [");
        let rows = table["srgb"].as_array().unwrap_or(&empty);
        for row in rows {
            line(&format!("      {},", literal(row)));
        }
        line("    ],");
        line("  },");
    }
    line("} as const;");
    Ok(out)
}

/// The checked-in file equals a fresh generation.
pub fn stale_finding(fresh: &str, checked_in: &str) -> Option<String> {
    (fresh != checked_in)
        .then(|| format!("{GENERATED_TS} is stale: run cargo xtask codegen and commit the result"))
}

