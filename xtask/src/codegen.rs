//! `cargo xtask codegen` (ADR-0005 section 2): the types of the body contract in
//! `sim-core` are generated from `contracts/body.json`, checked in and compared with a
//! fresh generation in the gate. The hash of the contract file per version lives in
//! `contracts/body.hashes.json`.

use serde_json::{Map, Value};
use std::fmt::Write;
use std::path::Path;
use std::process::Command;

use crate::contract;

/// Where the generated types live, relative to the repository root.
pub const GENERATED_FILE: &str = "crates/sim-core/src/body_contract/generated.rs";

/// The Rust name of a parameter key: `body_form_age` becomes `BodyFormAge`.
pub fn variant_name(key: &str) -> String {
    key.split('_')
        .map(|part| {
            let mut chars = part.chars();
            let first = chars.next().map(|c| c.to_ascii_uppercase());
            first.into_iter().chain(chars).collect::<String>()
        })
        .collect()
}

/// Methods of `BodyParams` beside the getters: a parameter with such a key would define
/// the name twice.
const TAKEN_NAMES: [&str; 2] = ["get", "slot"];

/// Keys whose generated names collide. `xtask` builds the generated file, so a file that
/// does not compile would lock out the tool that writes it. A key that is a Rust keyword
/// never gets that far: rustfmt refuses the file.
fn name_findings(keys: &[String]) -> Vec<String> {
    let mut findings = Vec::new();
    for (index, key) in keys.iter().enumerate() {
        if TAKEN_NAMES.contains(&key.as_str()) {
            findings.push(format!(
                "parameter {key}: the generated type has a method of this name"
            ));
        }
        let name = variant_name(key);
        if let Some(other) = keys[..index]
            .iter()
            .find(|other| variant_name(other) == name)
        {
            findings.push(format!(
                "parameters {other} and {key} share the Rust name {name}"
            ));
        }
    }
    findings
}

/// A number of the contract as an f64 literal: 25 becomes `25.0`, -4 becomes `-4.0`.
fn literal(value: &Value) -> String {
    format!("{:?}", value.as_f64().unwrap_or(f64::NAN))
}

/// The source of the generated types, before rustfmt. `Err` with the findings if the
/// contract does not pass its check: then nothing is generated.
pub fn generate(body_json: &str, source_hash: u64) -> Result<String, Vec<String>> {
    let findings = contract::schema_findings(body_json);
    if !findings.is_empty() {
        return Err(findings);
    }
    let body: Value = serde_json::from_str(body_json).map_err(|error| vec![error.to_string()])?;
    let version = body["contract_version"].as_str().unwrap_or_default();
    let empty = Vec::new();
    let parameters: Vec<&Map<String, Value>> = body["parameters"]
        .as_array()
        .unwrap_or(&empty)
        .iter()
        .filter_map(Value::as_object)
        .collect();
    let text = |parameter: &Map<String, Value>, field: &str| {
        parameter[field].as_str().unwrap_or_default().to_string()
    };
    let keys: Vec<String> = parameters
        .iter()
        .map(|parameter| text(parameter, "key"))
        .collect();
    let findings = name_findings(&keys);
    if !findings.is_empty() {
        return Err(findings);
    }
    let count = parameters.len();
    let mut out = String::new();
    // Writing into a String cannot fail.
    let mut line = |text: &str| {
        let _ = writeln!(out, "{text}");
    };
    line("// Generated by `cargo xtask codegen` from contracts/body.json. Do not edit.");
    line("");
    line("//! The types of the body contract (ADR-0005): one entry per parameter of");
    line("//! `contracts/body.json`. Parameters are addressed by their key, never by position.");
    line("");
    line("use serde::ser::{Serialize, SerializeMap, Serializer};");
    line("");
    line("/// The version of the contract these types come from.");
    line(&format!(
        "pub const CONTRACT_VERSION: &str = \"{version}\";"
    ));
    line("");
    line("/// `stable_hash64` over the bytes of `contracts/body.json`.");
    line(&format!(
        "pub const SOURCE_HASH: u64 = 0x{source_hash:016x};"
    ));
    line("");
    line("/// A parameter of the body contract, in the order of the contract file. The variants");
    line("/// have no stable numbers and no order: both would be positional.");
    line("#[derive(Clone, Copy, Debug, PartialEq, Eq)]");
    line("pub enum BodyParamKey {");
    for parameter in &parameters {
        line(&format!("    /// {}", text(parameter, "description")));
        line(&format!("    {},", variant_name(&text(parameter, "key"))));
    }
    line("}");
    line("");
    line("/// Range (both ends inside) and default of a parameter.");
    line("#[derive(Clone, Copy, Debug, PartialEq)]");
    line("pub struct BodyParamSpec {");
    line("    pub min: f64,");
    line("    pub max: f64,");
    line("    pub default: f64,");
    line("}");
    line("");
    line("impl BodyParamKey {");
    line("    /// Every parameter, in the order of the contract file.");
    line(&format!("    pub const ALL: [BodyParamKey; {count}] = ["));
    for parameter in &parameters {
        line(&format!(
            "        BodyParamKey::{},",
            variant_name(&text(parameter, "key"))
        ));
    }
    line("    ];");
    line("");
    line("    /// The key as in `contracts/body.json`.");
    line("    pub const fn as_str(self) -> &'static str {");
    line("        match self {");
    for parameter in &parameters {
        let key = text(parameter, "key");
        line(&format!(
            "            BodyParamKey::{} => \"{key}\",",
            variant_name(&key)
        ));
    }
    line("        }");
    line("    }");
    line("");
    line("    /// The parameter with this key.");
    line("    pub fn from_key(key: &str) -> Option<BodyParamKey> {");
    line("        BodyParamKey::ALL");
    line("            .into_iter()");
    line("            .find(|candidate| candidate.as_str() == key)");
    line("    }");
    line("");
    line("    /// Range and default as in the contract.");
    line("    pub const fn spec(self) -> BodyParamSpec {");
    line("        match self {");
    for parameter in &parameters {
        line(&format!(
            "            BodyParamKey::{} => BodyParamSpec {{ min: {}, max: {}, default: {} }},",
            variant_name(&text(parameter, "key")),
            literal(&parameter["range"][0]),
            literal(&parameter["range"][1]),
            literal(&parameter["default"]),
        ));
    }
    line("        }");
    line("    }");
    line("}");
    line("");
    line("/// The visible body values of one sim at one moment: one number per parameter. Built");
    line("/// only by the checked ways of the contract module, so every value is finite and");
    line("/// inside its range.");
    line("#[derive(Clone, Copy, Debug, PartialEq)]");
    line("pub struct BodyParams {");
    for parameter in &parameters {
        line(&format!("    pub(super) {}: f64,", text(parameter, "key")));
    }
    line("}");
    line("");
    line("impl BodyParams {");
    line("    /// The neutral adult reference figure: every parameter at its default.");
    line("    pub const DEFAULT: BodyParams = BodyParams {");
    for parameter in &parameters {
        line(&format!(
            "        {}: {},",
            text(parameter, "key"),
            literal(&parameter["default"])
        ));
    }
    line("    };");
    for parameter in &parameters {
        let key = text(parameter, "key");
        line("");
        line(&format!("    /// {}", text(parameter, "description")));
        line(&format!("    pub const fn {key}(&self) -> f64 {{"));
        line(&format!("        self.{key}"));
        line("    }");
    }
    line("");
    line("    /// The value of the parameter `key`.");
    line("    pub const fn get(&self, key: BodyParamKey) -> f64 {");
    line("        match key {");
    for parameter in &parameters {
        let key = text(parameter, "key");
        line(&format!(
            "            BodyParamKey::{} => self.{key},",
            variant_name(&key)
        ));
    }
    line("        }");
    line("    }");
    line("");
    line("    /// The place of the parameter `key`, for the checked ways of the contract module.");
    line("    pub(super) fn slot(&mut self, key: BodyParamKey) -> &mut f64 {");
    line("        match key {");
    for parameter in &parameters {
        let key = text(parameter, "key");
        line(&format!(
            "            BodyParamKey::{} => &mut self.{key},",
            variant_name(&key)
        ));
    }
    line("        }");
    line("    }");
    line("}");
    line("");
    line("/// A map from key to number, so that no encoding is positional.");
    line("impl Serialize for BodyParams {");
    line("    fn serialize<S: Serializer>(&self, serializer: S) -> Result<S::Ok, S::Error> {");
    line("        let mut map = serializer.serialize_map(Some(BodyParamKey::ALL.len()))?;");
    line("        for key in BodyParamKey::ALL {");
    line("            map.serialize_entry(key.as_str(), &self.get(key))?;");
    line("        }");
    line("        map.end()");
    line("    }");
    line("}");
    Ok(out)
}

/// The edition of the workspace, from the one line `edition = "..."` of its manifest.
pub fn workspace_edition(cargo_toml: &str) -> Option<&str> {
    let mut editions = cargo_toml.lines().filter_map(|line| {
        line.strip_prefix("edition = \"")
            .and_then(|rest| rest.strip_suffix('"'))
    });
    let edition = editions.next()?;
    editions.next().is_none().then_some(edition)
}

/// `source` formatted by the rustfmt of the pinned toolchain, by way of a file in `dir`
/// (below the workspace root, so that a rustfmt.toml of the workspace applies). `cargo fmt
/// --check` and the freshness check then see the same bytes. A source that does not parse
/// is an error.
pub fn format(dir: &Path, edition: &str, source: &str) -> Result<String, String> {
    let path = dir.join("generated.rs");
    std::fs::create_dir_all(dir)
        .and_then(|()| std::fs::write(&path, source))
        .map_err(|error| format!("cannot write {}: {error}", path.display()))?;
    let output = Command::new("rustfmt")
        .args(["--edition", edition])
        .arg(&path)
        .output()
        .map_err(|error| format!("cannot run rustfmt: {error}"))?;
    if !output.status.success() {
        return Err(format!(
            "rustfmt refuses the generated source:\n{}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    std::fs::read_to_string(&path)
        .map_err(|error| format!("cannot read {}: {error}", path.display()))
}

/// ADR-0005 section 7, check 4: the checked-in file equals a fresh generation.
pub fn stale_finding(fresh: &str, checked_in: &str) -> Option<String> {
    (fresh != checked_in).then(|| {
        format!("{GENERATED_FILE} is stale: run cargo xtask codegen and commit the result")
    })
}

/// The entries of `contracts/body.hashes.json`: version to 16 lower-case hex digits.
fn hash_entries(hashes_json: &str) -> Result<Map<String, Value>, String> {
    let Ok(Value::Object(entries)) = serde_json::from_str::<Value>(hashes_json) else {
        return Err("body.hashes.json is not a JSON object".to_string());
    };
    for (version, hash) in &entries {
        let lower_hex = |b: u8| b.is_ascii_digit() || (b'a'..=b'f').contains(&b);
        let valid = contract::is_version(version)
            && hash
                .as_str()
                .is_some_and(|hash| hash.len() == 16 && hash.bytes().all(lower_hex));
        if !valid {
            return Err(format!(
                "body.hashes.json: the entry {version} must map a version to 16 hex digits"
            ));
        }
    }
    Ok(entries)
}

/// ADR-0005 section 7, check 2: the hash of `contracts/body.json` equals the entry of its
/// version in `contracts/body.hashes.json`.
pub fn hash_findings(hashes_json: &str, version: &str, hash: u64) -> Vec<String> {
    let entries = match hash_entries(hashes_json) {
        Ok(entries) => entries,
        Err(finding) => return vec![finding],
    };
    let now = format!("{hash:016x}");
    match entries.get(version).and_then(Value::as_str) {
        None => vec![format!(
            "body.hashes.json has no entry for {version}: run cargo xtask codegen"
        )],
        Some(recorded) if recorded != now => vec![format!(
            "body.hashes.json records {recorded} for {version}, contracts/body.json hashes to {now}: a changed contract needs a new version"
        )],
        Some(_) => Vec::new(),
    }
}

/// The text of `contracts/body.hashes.json` with the entry of `version` set to `hash`.
pub fn with_hash(hashes_json: &str, version: &str, hash: u64) -> Result<String, String> {
    let mut entries = hash_entries(hashes_json)?;
    entries.insert(version.to_string(), Value::String(format!("{hash:016x}")));
    let text = serde_json::to_string_pretty(&Value::Object(entries))
        .map_err(|error| format!("cannot write body.hashes.json: {error}"))?;
    Ok(text + "\n")
}

