//! The descriptor's check on hand-written values (the shapes follow the format, the values
//! are arbitrary) and its TypeScript.

use serde_json::json;

use super::*;

fn person() -> Value {
    json!({
        "sim": 1, "lineage_key": "00000000000000ab", "sex": "female",
        "alleles": [{"locus": "core:disease_ar", "copies": [0, 1]}],
        "born": -5, "died": null, "cause_of_death": null, "emigrated": null,
        "mother": null, "father": null, "social_parents": [], "household": 1,
        "moved_out": false, "carer": null,
        "diseases": [{"disease": "core:disease_ar", "onset": 0.5, "affected": false}],
        "pool": null, "first_name": "Anna", "surname": "Wolf"
    })
}

fn pedigree(persons: Vec<Value>) -> Value {
    json!({
        "format_version": 5,
        "persons": persons,
        "partnerships": [{"partnership": 1, "woman": 1, "man": 2, "formed": 0, "ended": null, "ended_by": null, "kinship": 0.0}],
        "households": [{"household": 1, "formed": 0, "ended": null}]
    })
}

fn check(value: &Value) -> (Vec<String>, Seen) {
    let mut seen = Seen::new();
    let found = conforms(&descriptor(), "Pedigree", value, &mut seen);
    (found, seen)
}

#[test]
fn a_pedigree_of_the_format_conforms() {
    let (found, seen) = check(&pedigree(vec![person()]));
    assert_eq!(found, Vec::<String>::new());
    assert!(seen.contains("Person.sex=female"));
    assert!(!seen.contains("Person.died"));
}

#[test]
fn every_difference_is_named_with_its_path() {
    let mut extra = person();
    extra["nickname"] = json!("x");
    extra.as_object_mut().expect("an object").remove("carer");
    extra["born"] = json!(1.5);
    extra["sex"] = json!("other");
    extra["alleles"][0]["copies"] = json!("01");
    extra["pool"] = json!({"genome_key": 7});
    let (found, _) = check(&pedigree(vec![extra]));
    assert_eq!(
        found,
        [
            "$.persons[0].nickname: not a field of Person",
            "$.persons[0].sex: \"other\" is not Literal([\"female\", \"male\"])",
            "$.persons[0].alleles[0].copies: \"01\" is not List(Integer)",
            "$.persons[0].born: 1.5 is not Integer",
            "$.persons[0].carer: missing from Person",
            "$.persons[0].pool.genome_key: 7 is not Text",
            "$.persons[0].pool.born_pool: missing from FromPool",
            "$.persons[0].pool.arrived: missing from FromPool",
            "$.persons[0].pool.arrival_year: missing from FromPool",
            "$.persons[0].pool.mother_key: missing from FromPool",
            "$.persons[0].pool.father_key: missing from FromPool",
            "$.persons[0].pool.social_parent_keys: missing from FromPool",
        ]
    );
    let (found, _) = check(&json!([1]));
    assert_eq!(found, ["$: Pedigree is an object, not [1]"]);
}

/// Coverage: a nullable value counts once it is not null, an optional field once it is
/// there, a listed text once it appears.
#[test]
fn coverage_names_what_the_output_did_not_show() {
    let types = descriptor();
    let wanted = wanted(&types);
    assert!(wanted.contains("Person.died"));
    assert!(wanted.contains("Partnership.ended_by=emigration"));
    assert!(wanted.contains("Manifest.fork"));
    assert!(!wanted.contains("Person.sim"));
    let mut dead = person();
    dead["died"] = json!(100);
    dead["sex"] = json!("male");
    let (found, seen) = check(&pedigree(vec![person(), dead]));
    assert_eq!(found, Vec::<String>::new());
    let left = missing(&wanted, &seen);
    assert!(!left.contains(&"Person.died".to_owned()));
    assert!(!left.contains(&"Person.sex=male".to_owned()));
    assert!(left.contains(&"Person.emigrated".to_owned()));
    let mut seen = Seen::new();
    let manifest = json!({
        "format_version": 5, "core_version": 41, "data_hash": "0", "build_commit": "",
        "world_seed": "1", "closed_through": 9, "year_hashes": [{"year": 0, "hash": "a"}],
        "log_hash": "b", "fork": {"parent_log_hash": "c", "from_year": 1, "dropped_inputs": 0}
    });
    assert_eq!(
        conforms(&types, "Manifest", &manifest, &mut seen),
        Vec::<String>::new()
    );
    assert!(seen.contains("Manifest.fork"));
}

#[test]
fn the_typescript_follows_the_descriptor() {
    let ts = generate(&descriptor());
    assert!(ts.starts_with(
        "// Generated by `cargo xtask codegen` from xtask/src/export_types.rs. Do not edit.\n"
    ));
    for line in [
        "export type Pedigree = {",
        "  readonly persons: Person[];",
        "  readonly sex: \"female\" | \"male\";",
        "  readonly died: number | null;",
        "  readonly pool: FromPool | null;",
        "  readonly ended_by: \"death\" | \"separation\" | \"emigration\" | null;",
        "  readonly fork?: ForkInfo;",
        "  readonly social_parent_keys: string[];",
    ] {
        assert!(ts.lines().any(|l| l == line), "{line}");
    }
    assert_eq!(ts.matches("export type ").count(), descriptor().len());
}

