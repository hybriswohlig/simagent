//! The TypeScript types of the body contract: what `generate` writes for the repository's
//! contract, read back against `contracts/body.json` itself, and the stale check.

use std::path::Path;

use super::*;

fn contract() -> (String, Value) {
    let root = Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("the workspace");
    let text = crate::read(&root.join("contracts/body.json")).expect("the contract");
    let body = serde_json::from_str(&text).expect("JSON");
    (text, body)
}

#[test]
fn the_types_name_every_parameter_with_its_numbers() {
    let (text, body) = contract();
    let ts = generate(&text).expect("a valid contract");
    let lines: Vec<&str> = ts.lines().collect();
    assert_eq!(
        lines[0],
        "// Generated by `cargo xtask codegen` from contracts/body.json. Do not edit."
    );
    let version = format!(
        "export const BODY_CONTRACT_VERSION = {};",
        body["contract_version"]
    );
    assert!(lines.contains(&version.as_str()), "{version}");
    let parameters = body["parameters"].as_array().expect("parameters");
    assert_eq!(parameters.len(), 44);
    let start = lines
        .iter()
        .position(|l| *l == "export const BODY_PARAM_KEYS = [")
        .expect("keys");
    for (i, parameter) in parameters.iter().enumerate() {
        assert_eq!(lines[start + 1 + i], format!("  {},", parameter["key"]));
        let entry = format!(
            "  {}: {{ group: {}, unit: {}, min: {}, max: {}, default: {} }},",
            parameter["key"],
            parameter["group"],
            parameter["unit"],
            parameter["range"][0],
            parameter["range"][1],
            parameter["default"]
        );
        assert!(lines.contains(&entry.as_str()), "{entry}");
    }
    assert_eq!(lines[start + 1 + parameters.len()], "] as const;");
    assert!(!ts.contains("Math") && !ts.contains("://"));
}

/// Each material's table is the contract's: its own axes with their points (skin and hair
/// two, the iris one), then its colours row by row, nothing invented.
#[test]
fn each_melanin_table_is_the_contracts() {
    let (text, body) = contract();
    let ts = generate(&text).expect("a valid contract");
    let tables = body["melanin_to_srgb"].as_object().expect("tables");
    let axes = |material: &str| -> Vec<&str> {
        let table = tables[material].as_object().expect("a table");
        table
            .keys()
            .map(String::as_str)
            .filter(|k| *k != "srgb")
            .collect()
    };
    assert_eq!(axes("skin"), ["eumelanin", "pheomelanin"]);
    assert_eq!(axes("hair"), ["eumelanin", "pheomelanin"]);
    assert_eq!(axes("iris"), ["melanin"]);
    for (material, table) in tables {
        let mut block = vec![format!("  \"{material}\": {{")];
        for axis in axes(material) {
            block.push(format!("    \"{axis}\": {},", table[axis]));
        }
        block.push("    srgb: [".to_owned());
        for row in table["srgb"].as_array().expect("rows") {
            block.push(format!("      {row},"));
        }
        block.extend(["    ],".to_owned(), "  },".to_owned()]);
        assert!(
            ts.contains(&block.join("\n")),
            "{material}:\n{}",
            block.join("\n")
        );
    }
    assert!(!ts.contains("null"));
}

#[test]
fn an_invalid_contract_writes_nothing() {
    assert!(generate("{}").is_err());
    assert!(generate("not json").is_err());
}

#[test]
fn a_stale_file_is_named() {
    assert_eq!(stale_finding("a", "a"), None);
    assert_eq!(
        stale_finding("a", "b"),
        Some(
            "web/src/generated/body.ts is stale: run cargo xtask codegen and commit the result"
                .to_owned()
        )
    );
}
